"""Where the distributor lifecycle table lives: docs/, not beside the design.

At the project root it is Stage 0 input, kept out of the BOM only by a name
list (project_manifest.GENERATED_MARKDOWN). docs/ is read by no stage.
"""

from __future__ import annotations

import json
from pathlib import Path

from blpl.core import project_manifest
from blpl.core import stage8_review as s8


def test_a_new_project_keeps_its_lifecycle_table_in_docs(tmp_path: Path) -> None:
    assert project_manifest.lifecycle_table(tmp_path) == tmp_path / "docs" / "lifecycle.md"


def test_a_table_still_at_the_root_is_used_where_it_is(tmp_path: Path) -> None:
    """Its person-owned columns are not regenerated by an audit, so a run
    starting a fresh one in docs/ would orphan what people recorded."""
    (tmp_path / "lifecycle.md").write_text("| MPN |\n|---|\n", encoding="utf-8")
    assert project_manifest.lifecycle_table(tmp_path) == tmp_path / "lifecycle.md"


def test_once_moved_the_docs_table_wins_over_a_leftover(tmp_path: Path) -> None:
    (tmp_path / "lifecycle.md").write_text("old", encoding="utf-8")
    (tmp_path / "docs").mkdir()
    (tmp_path / "docs" / "lifecycle.md").write_text("new", encoding="utf-8")
    assert project_manifest.lifecycle_table(tmp_path) == tmp_path / "docs" / "lifecycle.md"


def test_stage8_names_the_docs_table_to_the_audit(tmp_path: Path, monkeypatch) -> None:
    """Left to itself kicad-happy writes <project>/lifecycle.md."""
    pipeline = tmp_path / ".pipeline"
    pipeline.mkdir()
    (pipeline / "bom.json").write_text(
        json.dumps({"project_id": "p", "schema_version": 1,
                    "rows": [{"local_id": "U1", "mpn": "M", "package": "P"}]})
    )
    sch = tmp_path / "b.kicad_sch"
    sch.write_text("(kicad_sch)")
    monkeypatch.setattr(s8, "_find_kicad_happy", lambda: tmp_path / "kh")
    seen: list[list[str]] = []

    def _fake_run(script, args, out_path, env=None, timeout=None):
        seen.append(list(args))
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps({"statistics": {}, "findings": []}))
        return {"ok": True, "skipped": False, "exit_code": 0, "report_json": str(out_path)}

    monkeypatch.setattr(s8, "_run_analyzer", _fake_run)
    s8.run(tmp_path, sch_path=sch, pcb_path=None, spice=False, lifecycle=True)

    args = seen[0]
    assert args[args.index("--lifecycle-table") + 1] == str(tmp_path / "docs" / "lifecycle.md")
    assert (tmp_path / "docs").is_dir()
