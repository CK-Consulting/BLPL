"""Stage 7: validation.

Runs three families of checks and writes a consolidated validation_report.json:

  1. KLC checks on any symbols auto-generated by Stage 3 (via kicad-library-utils).
  2. DRC on the Stage 6 .kicad_pcb via `kicad-cli pcb drc` (JSON output).
  3. Coverage summary carried over from stage2.

Tool availability is probed at runtime; missing tools produce `skipped` results,
not failures — a missing `kicad-cli` shouldn't break a CI that only wants KLC.

Assumed kicad-cli: v9 or v10. The flags used here (`--format json`,
`--exit-code-violations`, `--severity-all`, `--output`) are common to both.
If you see a flag mismatch, bump the version branching below.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from . import schema


# Three levels up: blpl/core/stage7_validate.py -> blpl/ -> board-layer-pipe-line/.
# This was parent.parent, so it looked for blpl/kicad-library-utils, which does
# not exist — meaning the KLC check has been reporting "skipped, tool not found"
# on every run since it was written, while the overall report still said ok.
_REPO_ROOT = Path(__file__).resolve().parents[2]
_CHECK_SYMBOL_PY = _REPO_ROOT / "kicad-library-utils" / "klc-check" / "check_symbol.py"


def _find_kicad_cli() -> str | None:
    for candidate in [
        shutil.which("kicad-cli"),
        "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli",
        "/usr/bin/kicad-cli",
    ]:
        if candidate and Path(candidate).exists():
            return candidate
    return None


def _kicad_cli_major(kicad_cli: str) -> int | None:
    """Return the KiCad major version (e.g., 9 or 10), or None if unparseable."""
    try:
        out = subprocess.run(
            [kicad_cli, "--version"], capture_output=True, text=True, check=False, timeout=10
        )
    except (OSError, subprocess.SubprocessError):
        return None
    text = (out.stdout or "") + (out.stderr or "")
    m = re.search(r"(\d+)\.(\d+)", text)
    return int(m.group(1)) if m else None


def _run_klc_symbol_checks(sym_files: list[Path]) -> dict:
    """Run kicad-library-utils/klc-check/check_symbol.py on each symbol file.

    The script exits non-zero if any KLC rule violations are found. We parse the
    per-file exit code and collect stderr/stdout verbatim for diagnostics.
    """
    if not _CHECK_SYMBOL_PY.exists():
        return {
            "ok": True,
            "skipped": True,
            "reason": f"klc-check not found at {_CHECK_SYMBOL_PY}",
            "results": [],
        }
    if not sym_files:
        return {"ok": True, "skipped": False, "results": [], "note": "no symbols to check"}

    results: list[dict] = []
    overall_ok = True
    for f in sym_files:
        proc = subprocess.run(
            [sys.executable, str(_CHECK_SYMBOL_PY), str(f), "-s"],
            capture_output=True,
            text=True,
            check=False,
            timeout=60,
        )
        ok = proc.returncode == 0
        overall_ok = overall_ok and ok
        # Keep a tail of output in the report so you can see why it failed.
        results.append(
            {
                "file": str(f),
                "ok": ok,
                "exit_code": proc.returncode,
                "stdout_tail": proc.stdout[-2000:] if proc.stdout else "",
                "stderr_tail": proc.stderr[-2000:] if proc.stderr else "",
            }
        )
    return {"ok": overall_ok, "skipped": False, "results": results}


def _run_drc(pcb_path: Path, output_json: Path) -> dict:
    """Run `kicad-cli pcb drc` on the PCB. Returns a result dict."""
    cli = _find_kicad_cli()
    if cli is None:
        return {
            "ok": True,
            "skipped": True,
            "reason": "kicad-cli not found in PATH or standard macOS location",
        }
    major = _kicad_cli_major(cli)
    if major is None:
        return {"ok": True, "skipped": True, "reason": "could not parse kicad-cli version"}

    output_json.parent.mkdir(parents=True, exist_ok=True)
    # Clear any previous run's report first. Everything below decides what
    # happened by asking whether this file exists, and kicad-cli writes nothing
    # when it cannot load the design at all — so a stale report was read as this
    # run's result and the *old* violation count was reported as current. That
    # turned a schematic kicad-cli refused to open ("Failed to load schematic",
    # exit 3) into a run whose numbers looked merely unchanged, which is the
    # worst way for an emitter bug to present.
    output_json.unlink(missing_ok=True)
    cmd = [
        cli,
        "pcb",
        "drc",
        # Planes are written unfilled; checked unfilled, every pad on one
        # reads as unconnected and the plane as if it were not there.
        "--refill-zones",
        "--format",
        "json",
        "--severity-all",
        "--exit-code-violations",
        "--output",
        str(output_json),
        str(pcb_path),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False, timeout=120)
    result: dict = {
        "ok": proc.returncode == 0,
        "skipped": False,
        "kicad_cli_major": major,
        "exit_code": proc.returncode,
        "report_json": str(output_json) if output_json.exists() else None,
        "stdout_tail": proc.stdout[-2000:] if proc.stdout else "",
        "stderr_tail": proc.stderr[-2000:] if proc.stderr else "",
    }
    if output_json.exists():
        try:
            data = json.loads(output_json.read_text())
            result["violation_count"] = len(data.get("violations", []))
            result["unconnected_count"] = len(data.get("unconnected_items", []))
            result["schematic_parity_count"] = len(data.get("schematic_parity", []))
        except json.JSONDecodeError:
            pass
    return result


def erc_violation_count(report: dict) -> int:
    """Every violation in a kicad-cli ERC report.

    KiCad 10 lists them per sheet (``sheets[].violations``) and has no
    top-level ``violations`` at all, so counting only the top level reported
    0 while kicad-cli said "Found 6 violations": a count that read as clean
    on a schematic that was not. Both places are counted, for an older
    report that puts them at the top.
    """
    top = len(report.get("violations") or [])
    per_sheet = sum(len(sheet.get("violations") or []) for sheet in report.get("sheets") or [])
    return top + per_sheet


def _run_erc(sch_path: Path, output_json: Path) -> dict:
    """Run `kicad-cli sch erc` on the schematic. Same shape of result as _run_drc."""
    cli = _find_kicad_cli()
    if cli is None:
        return {"ok": True, "skipped": True, "reason": "kicad-cli not found"}
    major = _kicad_cli_major(cli)
    if major is None:
        return {"ok": True, "skipped": True, "reason": "could not parse kicad-cli version"}

    output_json.parent.mkdir(parents=True, exist_ok=True)
    # Clear any previous run's report first. Everything below decides what
    # happened by asking whether this file exists, and kicad-cli writes nothing
    # when it cannot load the design at all — so a stale report was read as this
    # run's result and the *old* violation count was reported as current. That
    # turned a schematic kicad-cli refused to open ("Failed to load schematic",
    # exit 3) into a run whose numbers looked merely unchanged, which is the
    # worst way for an emitter bug to present.
    output_json.unlink(missing_ok=True)
    cmd = [
        cli,
        "sch",
        "erc",
        "--format",
        "json",
        "--severity-all",
        "--exit-code-violations",
        "--output",
        str(output_json),
        str(sch_path),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False, timeout=120)
    result: dict = {
        "ok": proc.returncode == 0,
        "skipped": False,
        "kicad_cli_major": major,
        "exit_code": proc.returncode,
        "report_json": str(output_json) if output_json.exists() else None,
        "stdout_tail": proc.stdout[-2000:] if proc.stdout else "",
        "stderr_tail": proc.stderr[-2000:] if proc.stderr else "",
    }
    if output_json.exists():
        try:
            data = json.loads(output_json.read_text())
            result["violation_count"] = erc_violation_count(data)
        except json.JSONDecodeError:
            pass
    return result


# --- project.yaml review.accept ---------------------------------------------
#
# ERC and DRC run with --severity-all and fail on anything, warnings included,
# so a finding that is true *and intended* failed the stage on every run. The
# case that forced this: a PWR_FLAG the schematic emitter adds to an undriven
# rail (emitter/sch.py, _undriven_power_nets) meeting a bidirectional pin that
# is tied to that rail on purpose, such as an IMU's SDO strapped to GND to pick
# its address. ERC calls that pin_to_pin, correctly, and nothing in the design
# is wrong. accept.py is the record of such waivers; Stage 7 now reads it too.

#: Entries whose rule starts with one of these apply here, and only those, so
#: a glob written for Stage 8 or the placement audit (``*``, ``*off_board``)
#: cannot waive an ERC or DRC violation by accident.
_RULE_PREFIXES = ("erc:", "drc:")

# "Symbol U6 Pin 1 [SDO, Bidirectional, Line]": ERC names a symbol per item.
_ERC_REF = re.compile(r"\bSymbol\s+(\S+)")
# "Pad A2 [VDD_3V3] of U5 on F.Cu", "Footprint U5": DRC names a footprint.
_DRC_REF = re.compile(r"\bof\s+(\S+)\s+on\b|^Footprint\s+(\S+)")
# "Track [VDD_3V3] on B.Cu": the net, on copper items. ERC's brackets hold a
# pin's name and type, not a net, so nets are read from DRC items only.
_DRC_NET = re.compile(r"^(?:Pad\s+\S+|Track|Via|Arc|Zone)\b[^\[]*\[([^\]]+)\]")


def _refs(descriptions: list[str], kind: str) -> list[str]:
    """The real parts a violation's items name, emitter-generated ones left out.

    ``#FLGnn`` and ``#PWRnn`` are symbols the schematic emitter adds and numbers
    itself, in whatever order it meets the rails, so the same flag is #FLG01 on
    one run and #FLG02 on the next. An entry that had to list them would stop
    matching as soon as an unrelated rail was added. Dropping them leaves the
    part the designer chose to wire that way, which is what the waiver is
    about. A violation that names *only* generated symbols has no parts, so
    only an entry without ``parts`` covers it.
    """
    out: list[str] = []
    for d in descriptions:
        if kind == "erc":
            m = _ERC_REF.search(d)
            ref = m.group(1) if m else None
        else:
            m = _DRC_REF.search(d)
            ref = (m.group(1) or m.group(2)) if m else None
        if ref and not ref.startswith("#") and ref not in out:
            out.append(ref)
    return out


def _nets(descriptions: list[str]) -> list[str]:
    out: list[str] = []
    for d in descriptions:
        m = _DRC_NET.search(d)
        # "<no net>" is KiCad saying there is none, not a net called that.
        if m and not m.group(1).startswith("<") and m.group(1) not in out:
            out.append(m.group(1))
    return out


def _findings(violations: list[dict], kind: str) -> list[dict]:
    """kicad-cli violations as accept.py findings, each violation kept whole."""
    out = []
    for v in violations:
        descs = [str(i.get("description") or "") for i in v.get("items") or []]
        out.append({
            **v,
            "rule_id": f"{kind}:{v.get('type') or ''}",
            "components": _refs(descs, kind),
            "nets": _nets(descs) if kind == "drc" else [],
        })
    return out


def _apply_accept(result: dict, report_path: Path, kind: str, entries: list[dict]) -> None:
    """Move the violations ``entries`` accept into ``result["accepted"]``.

    ``violation_count`` stays what kicad-cli found and ``accepted_count`` says
    how many of those are waived, so the record still shows every finding.
    Only the verdict moves: when every violation is accepted, the check passes.

    DRC's ``unconnected_items`` and ``schematic_parity`` are never waived. An
    open connection is a board that does not work, and a parity finding is a
    board that does not match its schematic; neither is a design choice, and a
    waiver that hid one would ship it. They keep failing the check.
    """
    entries = [e for e in entries if e["rule"].startswith(_RULE_PREFIXES)]
    if not entries or result.get("skipped") or not report_path.exists():
        return
    try:
        data = json.loads(report_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return
    violations = list(data.get("violations") or [])
    if kind == "erc":
        # Per sheet in KiCad 10, top level before it (erc_violation_count).
        for sheet in data.get("sheets") or []:
            violations += sheet.get("violations") or []
        unwaivable = 0
    else:
        unwaivable = len(data.get("unconnected_items") or []) + len(data.get("schematic_parity") or [])

    from . import accept

    open_, waived = accept.split(_findings(violations, kind), entries)
    if not waived:
        return
    result["accepted"] = waived
    result["accepted_count"] = len(waived)
    # Exit 5 is kicad-cli's "violations found" (--exit-code-violations). Any
    # other non-zero code means the run itself went wrong, and a report that
    # happens to be on disk does not turn that into a pass.
    if not open_ and not unwaivable and result.get("exit_code") in (0, 5):
        result["ok"] = True


def _coverage_summary(coverage_path: Path) -> dict:
    if not coverage_path.exists():
        return {"ok": True, "skipped": True, "reason": "no coverage_report.json"}
    data = schema.load_json(coverage_path)
    s = data.get("summary", {})
    return {
        "ok": s.get("miss", 0) == 0,
        "skipped": False,
        "total": s.get("total", 0),
        "hit": s.get("hit", 0),
        "needs_variant": s.get("needs_variant", 0),
        "miss": s.get("miss", 0),
    }


def run(
    project_dir: Path,
    *,
    pcb_path: Path | None = None,
    sch_path: Path | None = None,
    generated_symbols_dir: Path | None = None,
    coverage_path: Path | None = None,
    board: str | None = None,
    project_config: dict | None = None,
) -> dict:
    """Run all Stage 7 checks and write validation_report.json into .pipeline/.

    ``project_config`` is the board's project.yaml. Its ``review.accept``
    entries with an ``erc:<type>`` or ``drc:<type>`` rule waive the ERC and
    DRC violations they cover (_apply_accept); without it nothing is waived.

    ``board`` qualifies every file this stage reads or writes, the way the
    rest of the pipeline does (``validation_report.sensor.json``). Without it
    a multi-board project's boards overwrote one report and read one
    another's coverage.
    """
    from .project_manifest import artifact_path

    project_dir = Path(project_dir)
    pipeline_dir = project_dir / ".pipeline"
    pipeline_dir.mkdir(parents=True, exist_ok=True)

    def _p(name: str) -> Path:
        return artifact_path(project_dir, name, board=board)

    gen_symbols = generated_symbols_dir or (project_dir / "generated" / "symbols")
    cov = coverage_path or _p("coverage_report")

    sym_files = sorted(gen_symbols.glob("*.kicad_sym")) if gen_symbols.exists() else []
    klc_result = _run_klc_symbol_checks(sym_files)

    erc_result: dict
    if sch_path is not None and sch_path.exists():
        erc_result = _run_erc(sch_path, _p("erc_report"))
    else:
        erc_result = {"ok": True, "skipped": True, "reason": "no .kicad_sch supplied"}

    drc_result: dict
    if pcb_path is not None and pcb_path.exists():
        drc_result = _run_drc(pcb_path, _p("drc_report"))
    else:
        drc_result = {"ok": True, "skipped": True, "reason": "no .kicad_pcb supplied"}

    from . import accept

    entries = accept.entries(project_config)
    _apply_accept(erc_result, _p("erc_report"), "erc", entries)
    _apply_accept(drc_result, _p("drc_report"), "drc", entries)

    cov_result = _coverage_summary(cov)

    # Why each connection is still open (triage.py), for the reviewer and the
    # chat agent: the DRC report says only that it is.
    drc_json = _p("drc_report")
    # Gone first: a report from an earlier board must not stand in for this
    # one when DRC is skipped, since the resolution skill acts on it.
    _p("open_connections").unlink(missing_ok=True)
    if not drc_result.get("skipped") and drc_json.exists():
        from . import autoroute, triage

        try:
            drc_data = json.loads(drc_json.read_text(encoding="utf-8"))
            route_report = _p("autoroute_report")
            fanout = {}
            if route_report.exists():
                fanout = json.loads(route_report.read_text(encoding="utf-8")).get("plane_fanout") or {}
            open_conn = triage.classify(
                drc_data,
                plane_nets=autoroute.plane_nets(pcb_path) if pcb_path else [],
                fanout_failed=fanout.get("failed"),
            )
            _p("open_connections").write_text(json.dumps(open_conn, indent=2) + "\n", encoding="utf-8")
            drc_result["open_connections"] = {"count": open_conn["count"], "by_kind": open_conn["by_kind"]}
        except (OSError, ValueError) as exc:
            drc_result["open_connections"] = {"error": str(exc)}

    overall_ok = klc_result["ok"] and erc_result["ok"] and drc_result["ok"] and cov_result["ok"]
    report = {
        "ok": overall_ok,
        "klc_symbols": klc_result,
        "erc": erc_result,
        "drc": drc_result,
        "coverage": cov_result,
    }
    _p("validation_report").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report
