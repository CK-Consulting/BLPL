"""The chat agent's tools for fixing a board's ERC and DRC findings on copies.

The erc-drc-resolution skill has the agent work through what a run left —
open connections, DRC violations, ERC errors — interactively with the user,
on ``<name>_edit.<ext>`` copies of the emitted KiCad project. The originals
are what the next run regenerates; the copies are where a person and the agent
fix this board. Three tools:

- ``make_edit_copies`` copies the latest emitted project under ``kicad/``.
- ``propose_kicad_edit`` turns a few targeted operations (move a footprint,
  add a via or a track, add a wire or a no-connect, delete an item) into an
  edit of one ``_edit`` file, applied by parsing and rewriting the file, and
  proposed for the user to accept like any other edit. A whole KiCad board is
  far too large to rewrite by hand, and a hand edit that unbalances one
  parenthesis still loads and silently changes what every later node means:
  so the operations are applied to the parsed tree, and a result that does not
  parse back is refused.
- ``run_checks_on_edit`` runs ERC or DRC on an ``_edit`` file and reports the
  counts by type, so the agent never claims a number it has not measured.
"""

from __future__ import annotations

import asyncio
import json
import shutil
import tempfile
import uuid
from collections import Counter
from pathlib import Path

from blpl.emitter import sexpr

from .toolspec import ToolContext, ToolDenied, ToolSpec

#: What an edit copy can be. The project file is JSON, the others s-expressions.
COPYABLE = (".kicad_pcb", ".kicad_sch", ".kicad_pro")
#: Files a copy needs beside it to resolve its libraries.
_SIDECARS = ("sym-lib-table", "fp-lib-table")
EDIT_SUFFIX = "_edit"


def is_edit_copy(path: Path) -> bool:
    return path.suffix in COPYABLE and path.stem.endswith(EDIT_SUFFIX)


def _rel(ctx: ToolContext, p: Path) -> str:
    return p.resolve().relative_to(ctx.project_dir.resolve()).as_posix()


def _published_dir(ctx: ToolContext, board: str | None) -> Path:
    """Where the emitted project is published: kicad/ for a single-board
    project, <board>/kicad/ for each board of a declared multi-board one.

    Only the root kicad/ was looked at, so every multi-board project was
    refused after a successful run (Codex, PR #50).
    """
    root = ctx.project_dir
    if board:
        if "/" in board or "\\" in board or board.startswith("."):
            raise ToolDenied(f"{board!r} is not a board name")
        kicad = root / board / "kicad"
        if not kicad.is_dir():
            raise ToolDenied(f"board {board!r} has no emitted project under {board}/kicad/ yet")
        return kicad
    if (root / "kicad").is_dir():
        return root / "kicad"
    boards = sorted(d.name for d in root.iterdir()
                    if d.is_dir() and not d.name.startswith(".") and (d / "kicad").is_dir())
    if len(boards) == 1:
        return root / boards[0] / "kicad"
    if boards:
        raise ToolDenied("this project publishes several boards (" + ", ".join(boards)
                         + "); say which with board")
    raise ToolDenied("there is no emitted project under kicad/ yet: run the pipeline through stage 6")


def _emitted(ctx: ToolContext, board: str | None = None) -> list[Path]:
    """The emitted project's files, originals only."""
    kicad = _published_dir(ctx, board)
    return sorted(p for p in kicad.iterdir()
                  if p.suffix in COPYABLE and not p.stem.endswith(EDIT_SUFFIX))


def _edit_file(ctx: ToolContext, name: str, suffixes: tuple[str, ...]) -> Path:
    raw = (name or "").strip().replace("\\", "/")
    if not raw or ".." in Path(raw).parts or raw.startswith("/"):
        raise ToolDenied("path must be a project-relative path to an _edit file, e.g. kicad/board_edit.kicad_pcb")
    target = (ctx.project_dir / raw).resolve()
    if not target.is_relative_to(ctx.project_dir.resolve()):
        raise ToolDenied(f"{name!r} is outside the project")
    if target.suffix not in suffixes or not target.stem.endswith(EDIT_SUFFIX):
        raise ToolDenied(
            f"{name!r} is not an edit copy ({'/'.join(suffixes)} ending in {EDIT_SUFFIX}). "
            "The emitted originals are regenerated by every run and are never edited; "
            "call make_edit_copies first and edit the copy.")
    if not target.is_file():
        raise ToolDenied(f"{raw} does not exist; call make_edit_copies first")
    return target


# ---------------------------------------------------------------- make copies


async def _make_edit_copies(ctx: ToolContext, args: dict) -> str:
    overwrite = bool(args.get("overwrite"))
    # Every source and destination is checked before anything is copied: a
    # refusal halfway through a batch had already replaced the earlier _edit
    # files, discarding their edits on a call reported as failed (Codex, PR #50).
    plan = []
    for src in _emitted(ctx, (str(args.get("board") or "").strip() or None)):
        # A link is refused, and the source is checked as well as the
        # destination: copying follows the link, and a kicad/ file pointing
        # outside the project would put that file in a readable copy (Codex,
        # PR #50).
        if src.is_symlink():
            raise ToolDenied(f"{src.parent.name}/{src.name} is a symbolic link; it is not copied")
        ctx.sandbox.check_read(src)
        dst = src.with_name(f"{src.stem}{EDIT_SUFFIX}{src.suffix}")
        # Nor through a link at the destination: copying follows it, so an
        # _edit link to board.md would have overwritten board.md (Codex, PR #50).
        if dst.is_symlink():
            raise ToolDenied(f"{dst.parent.name}/{dst.name} is a symbolic link; it is not written through")
        ctx.sandbox.check_write(dst)
        plan.append((src, dst))
    made, kept = [], []
    for src, dst in plan:
        if dst.exists() and not overwrite:
            kept.append(_rel(ctx, dst))
            continue
        shutil.copyfile(src, dst)
        made.append(_rel(ctx, dst))
    if not made and not kept:
        raise ToolDenied("kicad/ holds no .kicad_pcb, .kicad_sch or .kicad_pro to copy")
    lines = []
    if made:
        lines.append("Copied: " + ", ".join(made) + ".")
    if kept:
        lines.append("Already there, left as they are (pass overwrite to replace them, which "
                     "discards their edits): " + ", ".join(kept) + ".")
    lines.append("Edit only these copies. Re-running the pipeline regenerates the originals "
                 "beside them with the same problems; the copies are not updated by it.")
    return "\n".join(lines)


# ---------------------------------------------------------------- edits


def _net_ref(board: sexpr.Sexp, name: str) -> list:
    """How a track or via on this board names its net.

    A board with a top-level net table (``(net N "NAME")``, BLPL's emitter and
    KiCad before 10) refers to a net by its number alone — ``(net N)``; the name
    belongs only in the table, and a track carrying both does not load (Codex,
    PR #50). A KiCad 10 board has no table and names the net: ``(net "NAME")``.
    """
    for node in board:
        if isinstance(node, list) and node and node[0] == "net" and len(node) >= 3:
            if sexpr.unquote(str(node[2])) == name:
                return ["net", str(node[1])]
    return ["net", sexpr.quote(name)]


def _has_net(board: sexpr.Sexp, name: str) -> bool:
    """Whether the board has the net, in the net table or on anything.

    Searched through the whole tree: a KiCad 10 board has no net table, and its
    ``(net "NAME")`` nodes sit inside pads, tracks and zones, so a search of
    the top level refused every net there (Codex, PR #50).
    """
    stack = [board]
    while stack:
        node = stack.pop()
        if not isinstance(node, list) or not node:
            continue
        if node[0] == "net" and len(node) >= 2 and sexpr.unquote(str(node[-1])) == name:
            return True
        stack.extend(child for child in node[1:] if isinstance(child, list))
    return False


def _uuid() -> str:
    return sexpr.quote(str(uuid.uuid4()))


def _num(v, what: str) -> str:
    try:
        return f"{float(v):g}"
    except (TypeError, ValueError):
        raise ToolDenied(f"{what} must be a number, not {v!r}")


def _xy(v, what: str) -> tuple[str, str]:
    if not (isinstance(v, (list, tuple)) and len(v) == 2):
        raise ToolDenied(f"{what} must be [x, y] in mm")
    return _num(v[0], what), _num(v[1], what)


def _footprint(board: sexpr.Sexp, ref: str):
    for fp in sexpr.find_all(board, "footprint"):
        for prop in sexpr.find_all(fp, "property"):
            if len(prop) > 2 and sexpr.unquote(str(prop[1])) == "Reference" \
                    and sexpr.unquote(str(prop[2])) == ref:
                return fp
    raise ToolDenied(f"no footprint {ref!r} on this board")


def _delete(tree: sexpr.Sexp, item_uuid: str) -> str:
    want = item_uuid.strip().strip('"')
    for i, node in enumerate(tree):
        if not isinstance(node, list):
            continue
        u = sexpr.find(node, "uuid")
        if u is not None and sexpr.unquote(str(u[1])) == want:
            del tree[i]
            return str(node[0])
    raise ToolDenied(f"no top-level item with uuid {want}")


def _apply(tree: sexpr.Sexp, op: dict, kind: str) -> str:
    name = op.get("op")
    if name == "delete":
        return f"deleted {_delete(tree, str(op.get('uuid', '')))} {op.get('uuid')}"
    if kind == ".kicad_pcb":
        if name == "move_footprint":
            fp = _footprint(tree, str(op.get("ref", "")))
            at = sexpr.find(fp, "at")
            x, y = _num(op.get("x"), "x"), _num(op.get("y"), "y")
            rot = op.get("rot")
            new_at = ["at", x, y] + ([_num(rot, "rot")] if rot is not None else
                                     ([at[3]] if at is not None and len(at) > 3 else []))
            if at is None:
                fp.insert(2, new_at)
            else:
                at[:] = new_at
            return f"moved {op['ref']} to ({x}, {y})" + (f" rot {rot}" if rot is not None else "")
        if name in ("add_via", "add_track"):
            net = str(op.get("net", ""))
            if not _has_net(tree, net):
                raise ToolDenied(f"no net {net!r} on this board")
            if name == "add_via":
                x, y = _num(op.get("x"), "x"), _num(op.get("y"), "y")
                tree.append(["via", ["at", x, y], ["size", _num(op.get("size", 0.6), "size")],
                             ["drill", _num(op.get("drill", 0.3), "drill")],
                             ["layers", '"F.Cu"', '"B.Cu"'], _net_ref(tree, net), ["uuid", _uuid()]])
                return f"added a via on {net} at ({x}, {y})"
            (sx, sy), (ex, ey) = _xy(op.get("start"), "start"), _xy(op.get("end"), "end")
            layer = str(op.get("layer", "F.Cu"))
            tree.append(["segment", ["start", sx, sy], ["end", ex, ey],
                         ["width", _num(op.get("width", 0.25), "width")], ["layer", sexpr.quote(layer)],
                         _net_ref(tree, net), ["uuid", _uuid()]])
            return f"added a {layer} track on {net} from ({sx}, {sy}) to ({ex}, {ey})"
    if kind == ".kicad_sch":
        if name == "add_wire":
            (sx, sy), (ex, ey) = _xy(op.get("start"), "start"), _xy(op.get("end"), "end")
            tree.append(["wire", ["pts", ["xy", sx, sy], ["xy", ex, ey]],
                         ["stroke", ["width", "0"], ["type", "default"]], ["uuid", _uuid()]])
            return f"added a wire from ({sx}, {sy}) to ({ex}, {ey})"
        if name == "add_no_connect":
            x, y = _num(op.get("x"), "x"), _num(op.get("y"), "y")
            tree.append(["no_connect", ["at", x, y], ["uuid", _uuid()]])
            return f"added a no-connect at ({x}, {y})"
    raise ToolDenied(f"operation {name!r} is not available for {kind} files")


async def _propose_kicad_edit(ctx: ToolContext, args: dict) -> str:
    from ..chat import ProposalStore, sha_of

    target = _edit_file(ctx, str(args.get("path", "")), (".kicad_pcb", ".kicad_sch"))
    ctx.sandbox.check_write(target)
    ops = args.get("operations")
    if not isinstance(ops, list) or not ops:
        raise ToolDenied("operations must be a non-empty list")
    current = target.read_text(encoding="utf-8")
    try:
        tree = sexpr.parse(current)
    except Exception as exc:  # noqa: BLE001
        raise ToolDenied(f"{_rel(ctx, target)} does not parse as it stands ({exc}); nothing can be "
                         "edited on top of it")
    done = [_apply(tree, op if isinstance(op, dict) else {}, target.suffix) for op in ops]
    new_content = sexpr.dump_top(tree)
    # Read back: an edit that does not parse is never proposed.
    try:
        sexpr.parse(new_content)
    except Exception as exc:  # noqa: BLE001
        raise ToolDenied(f"the edited file would not parse ({exc}); nothing proposed")
    rel = _rel(ctx, target)
    proposal = ProposalStore(ctx.project_dir).create(
        path=rel, new_content=new_content,
        rationale=str(args.get("rationale", "")) or "; ".join(done),
        base_sha=sha_of(current), conversation=ctx.conversation,
    )
    return (f"Proposed an edit to {rel} (proposal {proposal.id}): " + "; ".join(done) + ". "
            "The user must accept it before anything is written. After it is accepted, "
            "run_checks_on_edit measures the result.")


# ---------------------------------------------------------------- checks


async def _run_checks_on_edit(ctx: ToolContext, args: dict) -> str:
    from blpl.core import stage7_validate

    target = _edit_file(ctx, str(args.get("path", "")), (".kicad_pcb", ".kicad_sch"))
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "report.json"
        # kicad-cli runs for up to two minutes; on the event loop that stalls
        # every request, stream and chat the worker serves (Codex, PR #50).
        if target.suffix == ".kicad_pcb":
            result = await asyncio.to_thread(stage7_validate._run_drc, target, out)
            check = "DRC"
        else:
            result = await asyncio.to_thread(stage7_validate._run_erc, target, out)
            check = "ERC"
        if result.get("skipped"):
            return f"{check} did not run: {result.get('reason')}"
        if not out.exists():
            # kicad-cli could not load the file, so it wrote no report. That is a
            # failed check, never a clean one: read as an empty report it said
            # "0 violations" about a file KiCad cannot open (Codex, PR #50).
            detail = (result.get("stderr_tail") or result.get("stdout_tail") or "").strip()
            return (f"{check} FAILED on {_rel(ctx, target)}: kicad-cli exited "
                    f"{result.get('exit_code')} and wrote no report, so the file probably does "
                    f"not load. {detail[-800:]}")
        data = json.loads(out.read_text(encoding="utf-8"))
    parity = []
    if check == "DRC":
        violations = data.get("violations") or []
        unconnected = data.get("unconnected_items") or []
        # Where the board disagrees with its schematic: a DRC failure that
        # sits in its own list, and was read as clean without it (Codex, PR #50).
        parity = data.get("schematic_parity") or []
    else:
        # Both places: KiCad 10 nests a schematic's violations under each sheet,
        # and older reports (and the ones stage7 parses) keep them at the root.
        # Reading only one reported "0 violations" on a failing schematic
        # (Codex, PR #50).
        violations = list(data.get("violations") or []) + [
            v for s in data.get("sheets") or [] for v in s.get("violations") or []]
        unconnected = []
    by_type = Counter(f"{v.get('severity', '?')}:{v.get('type', '?')}" for v in violations)
    lines = [f"{check} on {_rel(ctx, target)}: {len(violations)} violation(s)"
             + (f", {len(unconnected)} unconnected item(s), {len(parity)} schematic parity "
                "finding(s)" if check == "DRC" else "") + "."]
    lines += [f"  {n} × {t}" for t, n in by_type.most_common()]
    shown = [v for v in violations if v.get("severity") == "error"][:15] or violations[:15]
    for v in shown:
        items = "; ".join(i.get("description", "") for i in v.get("items") or [])
        lines.append(f"- {v.get('type')}: {v.get('description')} — {items}")
    for p in parity[:15]:
        items = "; ".join(i.get("description", "") for i in p.get("items") or [])
        lines.append(f"- schematic parity: {p.get('type')}: {p.get('description')} — {items}")
    for u in unconnected[:15]:
        items = " ↔ ".join(i.get("description", "") for i in u.get("items") or [])
        lines.append(f"- unconnected: {items}")
    return "\n".join(lines)


# ---------------------------------------------------------------- run logs


def _runs_dir() -> Path:
    import os

    return Path(os.environ.get("BLPL_DATA_ROOT", "/app/data")) / "runs"


async def _read_run_log(ctx: ToolContext, args: dict) -> str:
    """A pipeline run's log, for a run of this project only.

    Run logs live outside the project (``data/runs``), where the agent's file
    tools cannot reach, so "Ask chat agent about this run" pointed it at
    evidence it could not read (Codex, PR #50).
    """
    from .. import runqueue
    from ..db import SessionFactory
    from ..models import Project, Run

    run_id = str(args.get("run_id") or "").strip()
    if not run_id:
        raise ToolDenied("run_id is required (the id shown in Run history, e.g. run_0e01cad37255)")
    with SessionFactory() as session:
        run = session.get(Run, run_id)
        project = session.get(Project, run.project_id) if run is not None else None
        if run is None or project is None or project.name != ctx.project_id:
            raise ToolDenied(f"no run {run_id} in this project")
        header = (f"Run {run.id} ({run.kind}): {run.status}, exit {run.exit_code}, "
                  f"started {run.started_at}, ended {run.ended_at}")
    path = runqueue.log_path(_runs_dir(), run_id)
    if not path.is_file():
        return header + "\n(no log was written for this run)"
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    limit = max(20, min(int(args.get("tail") or 400), 2000))
    shown = lines[-limit:]
    cut = f"(last {len(shown)} of {len(lines)} lines)\n" if len(lines) > len(shown) else ""
    return header + "\n" + cut + "\n".join(shown)


