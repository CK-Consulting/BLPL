class ProjectError(RuntimeError):
    """A git or filesystem operation on a project failed. Carries the git stderr
    so the UI can show what actually went wrong instead of a generic 500."""


# What a pull or push says when another one, or a change of remote, held the
# repository's origin lock for longer than it would wait (see _remote_lock).
_BUSY = "another pull, push or change of remote is in progress for this project; try again"


# Paths that are always changing and are never work anyone would lose: the
# conversation log grows on every turn, the usage ledger on every call, and
# .pipeline/ is regenerated by the next run. They are still committed — see
# commit_all — but they must not drive the "uncommitted" badge.
#
# They did, and that made the badge useless. It was lit permanently, because
# having a conversation dirties the tree, so it said "you have talked to the
# assistant" while appearing to say "you have unsaved design work". A warning
# that is always on is not a warning, and this one was sitting next to the
