# What a server says, lowercased, when it lets a credential read but not push:
# a 403 on receive-pack over HTTPS, a service it will not run for this user,
# a provider's own "denied". Checked alongside _AUTH_FAILURES.
_WRITE_REFUSALS = (
    "returned error: 403",
    "service not enabled",
    "not allowed to push",
    "denied",
    "write access",
    "read-only",
    "read only",
)


@dataclass(frozen=True)
class RemoteProbe:
    #: ok | auth_failed | not_found | read_only | error
    status: str
    #: The remote holds no refs at all. Only meaningful when status is ok.
    empty: bool
    message: str


# Substrings of git's stderr, lowercased, that mean the credential was the
# problem — over HTTPS (401/403, "authentication failed", a prompt git was told
# not to show) and over SSH ("permission denied (publickey)"). A provider that
# answers 404 for a private repository the token cannot see lands in not-found
# below, which is also what it is from where the user stands.
_AUTH_FAILURES = (
    "authentication failed",
    "could not read username",
    "could not read password",
    "terminal prompts disabled",
    "permission denied",
    "invalid username or password",
    "http basic: access denied",
    "the requested url returned error: 401",
    "the requested url returned error: 403",
)
_NOT_FOUND = (
    "repository not found",
    "not found",
    "does not appear to be a git repository",
    "the requested url returned error: 404",
    "no such file or directory",
)


def _porcelain_status(xy: str) -> str:
    """Map a two-char `git status --porcelain` code to a human word."""
    if xy == "??":
        return "untracked"
    code = xy.strip()
    if "D" in code:
        return "deleted"
    if "A" in code:
        return "added"
    if "R" in code:
        return "renamed"
    return "modified"
